function hash(input: string): number {
  let value = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    value ^= input.charCodeAt(i);
    value = Math.imul(value, 16777619);
  }
  return value >>> 0;
}

/** 当前级别为主、下一级别为辅（约三成），既不背得太轻松，也不至于全篇生词 */
export function levelsForPlan(levelId: string): KoLevel[] {
  const current = (KO_LEVEL_ORDER.includes(levelId as KoLevel) ? levelId : 'ko1') as KoLevel;
  const index = KO_LEVEL_ORDER.indexOf(current);
  const next = KO_LEVEL_ORDER[index + 1];
  return next ? [current, next] : [current];
}

export function pickKoWords(options: {
  levelId: string;
  seed: string;
  count: number;
  exclude?: Set<string>;
}): KoWord[] {
  const { levelId, seed, count, exclude } = options;
  const levels = levelsForPlan(levelId);

  // 每个级别先排「没进过词汇本」的词，再排已学过的词：
  // 整级导入后不会因为「都被排除」而只剩下一级别的进阶词，级别配比保持稳定。
  const buckets = levels.map((level) => {
    const pool = KO_WORDS.filter((word) => word.level === level);
    const bySeed = (a: KoWord, b: KoWord) => hash(seed + a.term) - hash(seed + b.term);
    const fresh = pool.filter((word) => !(exclude?.has(word.term) ?? false)).sort(bySeed);
    const seen = pool.filter((word) => exclude?.has(word.term) ?? false).sort(bySeed);
    return [...fresh, ...seen];
  });

  const picked: KoWord[] = [];
  const used = new Set<string>();
  let round = 0;
  while (picked.length < count && round < 200) {
    let added = false;
    for (let i = 0; i < buckets.length; i += 1) {
      // 主级别每轮取，辅级别隔轮取 → 混排比例约 2:1
      if (i > 0 && round % 2 === 1) continue;
      const bucket = buckets[i];
      const next = bucket[round];
      if (next && !used.has(next.term)) {
        used.add(next.term);
        picked.push(next);
        added = true;
        if (picked.length >= count) break;
      }
    }
    if (!added && buckets.every((bucket) => bucket[round] === undefined)) break;
    round += 1;
  }

  return picked.slice(0, count);
}
