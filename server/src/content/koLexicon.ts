function build(): KoWord[] {
  const words: KoWord[] = [];
  for (const [level, rows] of Object.entries(KO_LEVEL_ROWS) as Array<[KoLevel, Row[]]>) {
    for (const [term, roman, pos, cn, mnemonic, example, exampleCn, theme] of rows) {
      words.push({ term, roman, pos, cn, mnemonic, example, exampleCn, theme, level });
    }
  }
  return words;
}

