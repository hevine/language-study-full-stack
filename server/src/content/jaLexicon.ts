function build(level: JaLevel, rows: Row[]): JaWord[] {
  return rows.map((row) => ({
    term: row[0],
    kana: row[1],
    pos: row[2],
    cn: row[3],
    mnemonic: row[4],
    example: row[5],
    exampleCn: row[6],
    theme: row[7],
    level,
  }));
}

